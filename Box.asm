// Box.asm  -  K = 16
// Black box while any key is pressed, white when released.
// Start row 16, 20 rows tall, width = 16*((16 mod 4)+1) = 16 px = 1 word.
// Start address = 16384 + 32*16 = 16896

(LOOP)
  @KBD
  D=M
  @BLACK
  D;JNE
  @color
  M=0            
  @DRAW
  0;JMP
(BLACK)
  @color
  M=-1           
(DRAW)
  @16896         
  D=A
  @addr
  M=D            
  @20            
  D=A
  @rows
  M=D
(ROW)
  @1             
  D=A
  @cols
  M=D
  @addr
  D=M
  @p
  M=D            
(COL)
  @color
  D=M
  @p
  A=M
  M=D            
  @p
  M=M+1
  @cols
  M=M-1
  D=M
  @COL
  D;JGT
  @32
  D=A
  @addr
  M=D+M          
  @rows
  M=M-1
  D=M
  @ROW
  D;JGT
  @LOOP
  0;JMP
